#!/usr/bin/env python3
"""Build assets/theme-r4.css (loaded after theme.css and theme-r3.css).

1. Small accessibility fixes (all screen sizes).
2. Tablets (750-1023px): reuse every phone rule (max-width: 749px) from theme.css,
   theme-r3.css and the section stylesheets, at a fixed scale in a centered column,
   so text stays readable instead of shrinking with the desktop layout.

Run after src/build.py:  python3 src/build_r4.py
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent

def phone_blocks(css):
    out, i = [], 0
    while True:
        m = re.search(r'@media \(max-width: 749px\)\s*\{', css[i:])
        if not m:
            return out
        s = i + m.end(); d = 1; j = s
        while d:
            d += {'{': 1, '}': -1}.get(css[j], 0); j += 1
        out.append(css[s:j - 1]); i = j

def section_css(path):
    m = re.search(r'\{% stylesheet %\}(.*?)\{% endstylesheet %\}', (root / path).read_text(), re.S)
    return m.group(1) if m else ''

sources = [(root / 'assets/theme.css').read_text(), (root / 'assets/theme-r3.css').read_text()]
sources += [section_css(p) for p in ['sections/main-faq.liquid', 'sections/main-product.liquid', 'sections/o1-story-hero.liquid', 'snippets/band.liquid']]
body = re.sub(r'/\*.*?\*/', '', '\n'.join(b for s in sources for b in phone_blocks(s)), flags=re.S)
rules = []
for sel, decl in re.findall(r'([^{}]+)\{([^{}]*)\}', body):
    sel = ' '.join(sel.split())
    if sel == ':root':
        continue
    rules.append(', '.join('html body ' + x.strip() for x in sel.split(',')) + ' { ' + ' '.join(decl.split()) + ' }')

GLOBAL = """/* ---------- Accessibility fixes ---------- */
.o1-pcard__badge { background: #a8022a; }
.o1-pcard__price s, .o1-pdp__price s { opacity: .85; }
.o1-footer__legal a, .o1-pdp__crumbs a, .o1-ct__note a { display: inline-block; min-height: 24px; padding: 4px 0; line-height: 16px; }
"""
TABLET_EXTRA = """html:root { --u: 1.2px; }
html body .o1__canvas, html body .o1-page__inner, html body .o1-ct__inner, html body .o1-shop__head, html body .o1-shop__grid, html body .o1-pdp__canvas, html body .o1-pdp__desc, html body .o1-help__canvas { max-width: calc(390 * var(--u)); margin-left: auto; margin-right: auto; }
"""
TABLET_AFTER = """html body .o1-pcard__add { top: calc(268 * var(--u)); bottom: auto; }
"""
css = (GLOBAL + "\n/* ---------- Tablets (750-1023px): phone layout at a fixed scale, centered ----------\n"
       "   Generated by src/build_r4.py from the max-width: 749px rules. Do not edit by hand. */\n"
       "@media (min-width: 750px) and (max-width: 1023px) {\n" + TABLET_EXTRA + '\n'.join(rules) + '\n' + TABLET_AFTER + "}\n")
(root / 'assets/theme-r4.css').write_text(css)
print('built theme-r4.css', len(css), 'bytes,', len(rules), 'tablet rules')
